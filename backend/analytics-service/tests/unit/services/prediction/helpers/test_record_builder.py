import uuid

import pytest

from app.models.prediction import PropertyType, SourceType
from app.services.prediction.helpers.record_builder import build_prediction_record
from app.services.prediction.schemas.prediction import PredictionRequest

PRINCIPAL = uuid.uuid4()

BASE_REQ = PredictionRequest(
    area_m2=80.0,
    bedrooms=2,
    bathrooms=1.0,
    parking_spots=1,
    stratum=4,
    property_type=PropertyType.apartment,
    year_built=2010,
    lat=4.65,
    lon=-74.05,
    barrio_ideca="CHAPINERO",
)


def _build(**overrides):
    defaults = dict(
        req=BASE_REQ,
        predicted_price=500_000_000.0,
        model_version="v1",
        created_by=PRINCIPAL,
        source=SourceType.online,
    )
    return build_prediction_record(**{**defaults, **overrides})


def test_maps_all_req_fields():
    record = _build()
    assert record.area_m2 == BASE_REQ.area_m2
    assert record.bedrooms == BASE_REQ.bedrooms
    assert record.bathrooms == BASE_REQ.bathrooms
    assert record.parking_spots == BASE_REQ.parking_spots
    assert record.stratum == BASE_REQ.stratum
    assert record.property_type == BASE_REQ.property_type
    assert record.year_built == BASE_REQ.year_built
    assert record.lat == BASE_REQ.lat
    assert record.lon == BASE_REQ.lon
    assert record.barrio_ideca == BASE_REQ.barrio_ideca


def test_sets_prediction_metadata():
    record = _build(predicted_price=123.45, model_version="v2", source=SourceType.batch)
    assert record.predicted_price == 123.45
    assert record.model_version == "v2"
    assert record.source == SourceType.batch


def test_audit_fields_set_to_principal():
    record = _build()
    assert record.created_by == PRINCIPAL
    assert record.updated_by == PRINCIPAL


def test_property_id_propagated_from_req():
    prop_id = uuid.uuid4()
    req = BASE_REQ.model_copy(update={"property_id": prop_id})
    record = _build(req=req)
    assert record.property_id == prop_id


def test_property_id_none_by_default():
    record = _build()
    assert record.property_id is None


def test_record_has_autogenerated_id():
    r1 = _build()
    r2 = _build()
    assert r1.id != r2.id
